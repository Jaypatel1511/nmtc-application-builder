def test_word_properties_name_the_cde_and_the_package(rendered):
    from nmtcapp import __version__
    from nmtcapp.renderers._document_properties import document_title

    app, paths = rendered
    props = _docx_props(paths["word"])
    assert props["author"] == app.cde.name
    assert props["title"] == document_title(app)
    assert f"nmtc-application-builder v{__version__}" in props["comments"]
    assert props["created"].year >= 2026, props["created"]
    assert props["modified"] == props["created"]
    # Not invented: the profile carries none of these.
    assert props["subject"] == ""
    assert props["keywords"] == ""
    assert props["category"] == ""


def test_word_properties_carry_no_library_default(rendered):
    _app, paths = rendered
    props = _docx_props(paths["word"])
    leaked = {k: v for k, v in props.items()
              if isinstance(v, str) and "python-docx" in v.lower()}
    assert not leaked, f"python-docx's defaults still in the file: {leaked}"
    assert props["created"] != datetime.datetime(2013, 12, 23, 23, 15, tzinfo=datetime.timezone.utc), (
        "created is python-docx's template date, not the generation time"
    )


def test_excel_properties_name_the_cde_and_the_package(rendered):
    from nmtcapp import __version__
    from nmtcapp.renderers._document_properties import document_title

    app, paths = rendered
    props = _xlsx_props(paths["excel"])
    assert props["creator"] == app.cde.name
    assert props["title"] == document_title(app)
    assert f"nmtc-application-builder v{__version__}" in props["description"]
    assert props["subject"] is None
    assert props["keywords"] is None
    assert props["category"] is None
    assert props["created"] is not None and props["created"].year >= 2026


def test_excel_properties_carry_no_library_default(rendered):
    _app, paths = rendered
    props = _xlsx_props(paths["excel"])
    leaked = {k: v for k, v in props.items()
              if isinstance(v, str) and "openpyxl" in v.lower()}
    assert not leaked, f"openpyxl's defaults still in the file: {leaked}"


def test_the_title_is_built_from_what_the_profile_supplies():
    from nmtcapp.core.application import Application
    from nmtcapp.core.cde import CDEProfile
    from nmtcapp.renderers._document_properties import document_title

    cde = CDEProfile.sample()
    with_round = Application(cde=cde, requested_allocation=1.0, application_round="CY 2026")
    without = Application(cde=cde, requested_allocation=1.0)
    assert document_title(with_round) == f"{cde.name} — NMTC CY 2026 Allocation Application"
    assert document_title(without) == f"{cde.name} — NMTC Allocation Application"
    assert "None" not in document_title(without)
